import uuid

from fastapi import APIRouter, Depends, HTTPException, status
from sqlalchemy.orm import Session

from app.core.security import decode_access_token
from app.db.session import get_db
from app.models.exam import Exam
from app.models.exam_attempt import ExamAttempt, Question, Response
from app.models.grade import Grade, GradeStatus, GradingDetail, QuestionFeedback
from app.models.user import User
from app.schemas.grade import TranscriptEntryOut
from app.schemas.public_results import PublicResultsOut

router = APIRouter(prefix="/public", tags=["public-results"])


@router.get("/results/{token}", response_model=PublicResultsOut)
def get_public_results(token: str, db: Session = Depends(get_db)):
    """No login — the token itself is the credential (see
    core.security.create_grade_share_token), generated by the instructor
    and shared directly with the student. Re-checks `status == PUBLISHED`
    on every read (CLAUDE.md §7), not just trusting that a token was once
    issued — an instructor reverting a grade to review stops this from
    resolving immediately, even though the token itself is still a valid
    signature."""
    payload = decode_access_token(token)
    if payload is None or payload.get("role") != "grade_share":
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Results link not found")

    grade = db.get(Grade, uuid.UUID(payload["sub"]))
    if grade is None or grade.status != GradeStatus.published:
        raise HTTPException(status_code=status.HTTP_404_NOT_FOUND, detail="Results not available")

    attempt = db.get(ExamAttempt, grade.attempt_id)
    exam = db.get(Exam, attempt.exam_id)
    student = db.get(User, attempt.student_id) if attempt.student_id else None
    candidate_name = student.email if student else (attempt.candidate_name or attempt.candidate_id_number)

    details = db.query(GradingDetail).filter(GradingDetail.grade_id == grade.id).all()

    questions = (
        db.query(Question).filter(Question.attempt_id == attempt.id).order_by(Question.sequence).all()
    )
    feedback_by_question = {
        qf.question_id: qf for qf in db.query(QuestionFeedback).filter(QuestionFeedback.grade_id == grade.id)
    }
    transcript = []
    for q in questions:
        response = db.query(Response).filter(Response.question_id == q.id).first()
        qf = feedback_by_question.get(q.id)
        transcript.append(
            TranscriptEntryOut(
                sequence=q.sequence,
                question=q.text,
                is_followup=q.is_followup,
                is_generalization=q.is_generalization,
                is_graded=q.is_graded,
                difficulty=q.difficulty.value,
                answer=response.transcript_text if response else None,
                ai_score=qf.score if qf else None,
                ai_max_score=qf.max_score if qf else None,
                ai_feedback=qf.feedback if qf else None,
                ai_criterion=qf.criterion if qf else None,
                source_excerpt=q.source_excerpt,
                highlight_terms=q.highlight_terms,
            )
        )

    return PublicResultsOut(
        exam_name=exam.name,
        candidate_name=candidate_name,
        score=grade.instructor_score if grade.instructor_score is not None else grade.ai_score,
        max_score=grade.ai_max_score,
        strengths=grade.strengths,
        weaknesses=grade.weaknesses,
        instructor_feedback=grade.instructor_feedback,
        published_at=grade.published_at,
        details=details,
        transcript=transcript,
    )
